def start_keyboard():
    builder = InlineKeyboardBuilder()

    builder.button(
        text="🐈 Я готов",
        callback_data="start_quest"
    )

    return builder.as_markup()


def gift_keyboard(number):
    builder = InlineKeyboardBuilder()

    builder.button(
        text=f"🎁 Открыть подарок №{number}",
        callback_data=f"open_{number}"
    )

    return builder.as_markup()


def opened_keyboard(number):
    builder = InlineKeyboardBuilder()

    builder.button(
        text="❤️ Я открыл",
        callback_data=f"opened_{number}"
    )

    return builder.as_markup()


def listened_keyboard(number):
    builder = InlineKeyboardBuilder()

    builder.button(
        text="❤️ Я прослушал",
        callback_data=f"listened_{number}"
    )

    return builder.as_markup()


