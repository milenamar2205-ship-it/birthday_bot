@dp.callback_query(F.data.startswith("open_"))
async def open_gift(callback: CallbackQuery):

    user_id = callback.from_user.id

    create_user(user_id)

    number = int(callback.data.split("_")[1])

    current_gift = get_current_gift(user_id)

    if number != current_gift:

        await callback.answer(
            f"Сначала нужно открыть подарок №{current_gift} 😌",
            show_alert=True
        )

        return

    gift = GIFTS[number - 1]

    text = gift["text"]

    # Эта фраза только для первого подарка
    if number == 1:

        text += """
        
Когда действительно откроешь
нажми кнопку ниже.

Я слежу.
"""

    await callback.message.edit_text(
        text,
        reply_markup=opened_keyboard(number)
    )

    await callback.answer()


